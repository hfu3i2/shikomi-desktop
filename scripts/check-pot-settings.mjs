import assert from 'node:assert/strict';
import {createServer} from 'node:http';
import {readFile} from 'node:fs/promises';
import {resolve,sep,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createRequire} from 'node:module';
import {initialWorkspace,cleanReservation,localDate} from '../src/workspace.ts';
import {blankReservation} from '../src/domain.ts';
import {launchBoardBrowser} from '../worker/browser.mjs';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..'),dist=resolve(root,'dist');
const {chromium}=createRequire(resolve(root,'worker/package.json'))('playwright');
const server=createServer(async(req,res)=>{try{const url=new URL(req.url,'http://localhost');const p=resolve(dist,'.'+(url.pathname==='/'?'/index.html':decodeURIComponent(url.pathname)));if(!p.startsWith(dist+sep))throw Error('outside');res.setHeader('Content-Type',p.endsWith('.js')?'text/javascript':p.endsWith('.css')?'text/css':'text/html');res.end(await readFile(p));}catch{res.statusCode=404;res.end('Not found');}});
await new Promise(r=>server.listen(0,'127.0.0.1',r));let browser;
try{browser=await launchBoardBrowser(chromium,{channel:'chrome'},false);
 const page=await browser.newPage({viewport:{width:900,height:650}});
 const state=initialWorkspace();state.manual=[cleanReservation({...blankReservation(state.settings),people:3},localDate())];
 await page.addInitScript(s=>{if(!localStorage.getItem('portfolio.shikomi.workspace.v1'))localStorage.setItem('portfolio.shikomi.workspace.v1',JSON.stringify(s));},state);
 await page.goto('http://127.0.0.1:'+server.address().port);
 await page.getByRole('button',{name:'コース・料理の設定',exact:true}).click();
 await page.getByRole('button',{name:'鍋の種類',exact:true}).click();
 await page.getByRole('button',{name:'鍋の種類を追加',exact:true}).click();
 await page.getByLabel('新しい鍋の鍋名',{exact:true}).fill('寄せ鍋');
 await page.getByLabel('寄せ鍋の表示文字',{exact:true}).fill('寄');
 await page.getByLabel('寄せ鍋の判定キーワード',{exact:true}).fill('寄せ鍋、よせ鍋');
 await page.getByLabel('もつ鍋or水炊きの候補・寄せ鍋',{exact:true}).check();
 await page.getByRole('button',{name:'コース',exact:true}).click();
 await page.getByLabel('3500円コースの鍋種別',{exact:true}).selectOption({label:'寄せ鍋'});
 await page.getByRole('button',{name:'保存',exact:true}).click();
 await page.waitForFunction(()=>JSON.parse(localStorage.getItem('portfolio.shikomi.workspace.v1')).settings.potTypes?.some(t=>t.name==='寄せ鍋'));
 await page.reload();
 await page.getByRole('button',{name:'コース・料理の設定',exact:true}).click();
 await page.getByRole('button',{name:'鍋の種類',exact:true}).click();
 assert.equal(await page.getByLabel('寄せ鍋の表示文字',{exact:true}).inputValue(),'寄');
 await page.getByLabel('寄せ鍋の表示文字',{exact:true}).fill('寄せ');
 const row=page.locator('.pot-config').filter({has:page.getByLabel('寄せ鍋の鍋名',{exact:true})});
 assert.match(await row.innerText(),/3×1寄せ/);
 await row.scrollIntoViewIfNeeded();await page.screenshot({path:resolve(root,'pot-settings-v23.png')});
 await page.getByRole('button',{name:'保存',exact:true}).click();
 await page.getByRole('button',{name:'仕込み表',exact:true}).click();
 await page.locator('.reservation-item').first().click();
 await page.getByLabel('予約の鍋の種類',{exact:true}).selectOption({label:'寄せ鍋'});
 await page.getByRole('button',{name:'卓・台数を確認',exact:true}).click();await page.getByRole('button',{name:'印刷へ',exact:true}).click();
 assert.equal(await page.locator('.legacy-reservation-line strong').first().innerText(),'寄せ');
 assert.match(await page.locator('.legacy-reservation-line').first().innerText(),/3×1/);
 assert.match(await page.locator('.legacy-position-grid').innerText(),/寄せ鍋/);
 await page.getByRole('button',{name:'コース・料理の設定',exact:true}).click();
 await page.getByRole('button',{name:'鍋の種類',exact:true}).click();
 await page.getByLabel('寄せ鍋の鍋名',{exact:true}).fill('海鮮寄せ鍋');
 await page.getByRole('button',{name:'保存',exact:true}).click();
 assert.equal(await page.locator('.legacy-reservation-line strong').first().innerText(),'寄せ');
 assert.match(await page.locator('.legacy-position-grid').innerText(),/海鮮寄せ鍋/);
 console.log('Custom pot add, keywords, choice candidates, course assignment, label preview, save/reload, manual selection, print suffix and rename passed');
 await page.close();
}finally{await browser?.close();await new Promise(r=>server.close(r));}
